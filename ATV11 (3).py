media_geral = float(input("Digite a média final do estudante: "))

if media_geral >= 8:
    print (f"Sua média foi {media_geral:.2f} e você está apto para participar do processo seletivo da bolsa estudantil.")
else:
    print(f"Sua média foi {media_geral:.2f} e você não está qualificado para o processo seletivo da bolsa estudantil.")
